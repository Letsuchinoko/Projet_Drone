/* USER CODE BEGIN PV */
#define GPS_BUFFER_SIZE 256
uint8_t gps_rx_buffer[GPS_BUFFER_SIZE];
uint16_t gps_rx_index = 0;

int __io_putchar(int ch) {
    HAL_UART_Transmit(&huart2, (uint8_t *)&ch, 1, HAL_MAX_DELAY);
    return ch;
}
